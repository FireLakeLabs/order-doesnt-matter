import { parse, type Node } from 'acorn';
import { HARD_QUERY_MS } from '../engine/playback-limits';

export class ExecutionLimit extends Error {
  constructor() {
    super('This program exceeded its execution limit.');
  }
}

/** Cooperative control-flow bound, NOT a JavaScript sandbox. Covers authored
 * loops/recursion in evaluation and queries, including browser-only branches.
 * Native calls (e.g. a pathological regexp), generated code, hostile tampering,
 * and trigger-time/browser side effects cannot be interrupted by these checks.
 * Dynamic code and self-inspection are unsupported; known direct spellings are
 * refused below, but aliases/computed host access are not a security boundary.
 * Async continuations outside evaluation/query and trigger callbacks are unbounded.
 */
export class ExecutionBudget {
  private deadline = 0;
  private active = false;
  private failure?: ExecutionLimit;
  private turn?: ReturnType<typeof setTimeout>;
  private yielded = false;
  constructor(private now = () => performance.now()) {}
  begin() {
    this.active = true;
    this.deadline = this.now() + HARD_QUERY_MS;
    this.check();
    this.watchTurn();
  }
  end() {
    this.active = false;
    clearTimeout(this.turn);
  }
  check() {
    if (this.failure) throw this.failure;
    if (this.active && this.yielded) {
      this.deadline = this.now() + HARD_QUERY_MS;
      this.watchTurn();
    }
    if (this.active && this.now() > this.deadline) {
      this.failure = new ExecutionLimit();
      throw this.failure;
    }
  }
  // Only a yield to the event loop permits a fresh segment. Awaiting an already
  // resolved promise only queues a microtask and can otherwise starve the page.
  resumed<T>(value: T): T {
    this.check();
    return value;
  }
  private watchTurn() {
    clearTimeout(this.turn);
    this.yielded = false;
    this.turn = setTimeout(() => (this.yielded = true), 0);
  }
  run<T>(work: () => T): T {
    this.begin();
    try {
      const result = work();
      this.check(); // A nested queryArc/user catch must not turn failure into silence.
      return result;
    } finally {
      this.end();
    }
  }
}

// Insert before Strudel transpilation: labels, mini strings and implicit final
// return remain Strudel's job. No source is regenerated by our AST traversal.
export function boundedSource(source: string, binding: string): string {
  if (!/^[\w-]+$/.test(binding)) throw Error('Invalid execution binding');
  const ast = parse(source, { ecmaVersion: 2022, allowAwaitOutsideFunction: true });
  let name = '__odmExecution';
  while (source.includes(name)) name += '_';
  const edits = new Map<number, string[]>();
  const insert = (at: number, text: string) => {
    edits.set(at, [...(edits.get(at) ?? []), text]);
  };
  const check = `${name}.check();`;
  function body(node: Node) {
    if (node.type === 'BlockStatement') insert(node.start + 1, check);
    else {
      insert(node.start, `{${check}`);
      insert(node.end, '}');
    }
  }
  const dynamic = ['eval', 'Function', 'AsyncFunction', 'evaluate', 'evalScope', 'initStrudel'];
  function visit(node: Node) {
    const n = node as Node & {
      body?: Node;
      expression?: boolean;
      name?: string;
      property?: Node & { name?: string; value?: unknown };
    };
    if (
      (node.type === 'Identifier' && dynamic.includes(n.name!)) ||
      node.type === 'ImportExpression' ||
      (node.type === 'MemberExpression' &&
        [...dynamic, 'constructor'].includes(String(n.property?.name ?? n.property?.value)))
    )
      throw Error('Dynamic code is unsupported in bounded playback; edit this program as source.');
    if (/^(While|DoWhile|For|ForIn|ForOf)Statement$/.test(node.type)) body(n.body!);
    if (/^(FunctionDeclaration|FunctionExpression|ArrowFunctionExpression)$/.test(node.type)) {
      if (n.expression) {
        insert(n.body!.start, `(${name}.check(),(`);
        insert(n.body!.end, '))');
      } else {
        // Keep function directives (especially "use strict") in the prologue.
        const block = n.body as Node & { body: (Node & { directive?: string })[] };
        const directives = block.body.filter((statement) => statement.directive);
        insert(directives.at(-1)?.end ?? block.start + 1, `;${check}`);
      }
    }
    if (node.type === 'AwaitExpression') {
      insert(node.start, `${name}.resumed(`);
      insert(node.end, ')');
    }
    for (const value of Object.values(node)) {
      if (Array.isArray(value)) {
        for (const child of value) if (child && typeof child.type === 'string') visit(child);
      } else if (value && typeof value === 'object' && 'type' in value) visit(value as Node);
    }
  }
  visit(ast);
  let output = source;
  for (const [at, text] of [...edits].sort(([a], [b]) => b - a))
    output = output.slice(0, at) + text.join('') + output.slice(at);
  return `const ${name} = globalThis['${binding}']; ${check}\n${output}`;
}
